class Capability {
  final String num;
  final String code;
  final String title;
  final String desc;
  final String icon;
  final String spec;
  final String corner;
  final bool hasOrangeAccent;

  const Capability({
    required this.num,
    required this.code,
    required this.title,
    required this.desc,
    required this.icon,
    required this.spec,
    required this.corner,
    required this.hasOrangeAccent,
  });
}
