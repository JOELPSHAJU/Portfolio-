class Suite {
  final String id;
  final String category;
  final String title;
  final String tagline;
  final String price;
  final String period;
  final String badge;
  final String image;
  final String sqm;
  final String guests;
  final String view;
  final List<String> features;
  final String description;

  const Suite({
    required this.id,
    required this.category,
    required this.title,
    required this.tagline,
    required this.price,
    required this.period,
    required this.badge,
    required this.image,
    required this.sqm,
    required this.guests,
    required this.view,
    required this.features,
    required this.description,
  });
}
